import assert from 'node:assert/strict'

export async function checkWorkoutFeed(browser, baseURL) {
  const context = await browser.newContext({ locale: 'pt-BR', viewport: { width: 375, height: 812 }, reducedMotion: 'reduce' })
  const page = await context.newPage()
  page.setDefaultTimeout(10_000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const feed = page.getByRole('region', { name: 'Feed de exercícios do treino' })
  const card = id => feed.locator(`[data-exercise-id="${id}"]`)
  const done = (name, set = 1) => page.getByRole('button', { name: `Concluir ${name}, série ${set}`, exact: true })
  const openDay = name => page.locator('.training-day-card').filter({ hasText: name }).click()
  const skip = () => page.getByRole('button', { name: 'Pular descanso', exact: true }).click()
  const expectIndex = async index => page.waitForFunction(expected => {
    const feed = document.querySelector('.training-feed')
    return feed && Math.abs(feed.scrollTop - feed.children[expected].offsetTop) < 3 && document.querySelector('.feed-toolbar').innerText.includes(`Exercício ${expected + 1} de 7`)
  }, index)
  try {
    await page.clock.install({ time: new Date('2026-11-06T12:00:00-03:00') })
    await page.goto(baseURL)
    assert.deepEqual(await page.locator('.training-day-card h2').allTextContents(), ['Segunda-feira', 'Terça-feira', 'Quinta-feira', 'Sexta-feira'])
    assert.equal(await page.locator('.exercise-card').count(), 0)
    assert.equal(await page.getByRole('button', { name: 'Iniciar treino', exact: true }).count(), 0)
    await page.screenshot({ path: '/tmp/form-training-days-mobile.png', fullPage: true })
    await openDay('Corpo inteiro')
    await feed.waitFor()
    assert.equal(await feed.locator('.exercise-card').count(), 7)
    assert.equal(await feed.locator('input, select').count(), 0)
    assert.ok(await done('Agachamento búlgaro ou passada').isDisabled())
    assert.match(await card('bulgarian-lunge').innerText(), /3 séries\s*×\s*10–12 repetições/)
    await page.getByRole('button', { name: 'Iniciar treino', exact: true }).click()
    await expectIndex(0)
    const bounds = await done('Agachamento búlgaro ou passada').boundingBox()
    assert.ok(bounds && bounds.y >= 0 && bounds.y + bounds.height <= 812, 'Complete-set button fits the initial viewport')
    await page.screenshot({ path: '/tmp/form-workout-feed-mobile.png' })
    await done('Agachamento búlgaro ou passada').click()
    const rest = page.getByRole('dialog', { name: 'Hora de descansar' })
    await rest.waitFor()
    assert.match(await page.getByRole('timer').innerText(), /01:30/)
    assert.match(await rest.innerText(), /Série 2/)
    assert.equal(await page.getByRole('button', { name: 'Desmarcar Agachamento búlgaro ou passada, série 1', exact: true }).getAttribute('aria-pressed'), 'true')
    await page.screenshot({ path: '/tmp/form-workout-rest-mobile.png' })
    await page.clock.fastForward(5000)
    assert.match(await page.getByRole('timer').innerText(), /01:25/)
    await page.reload()
    await rest.waitFor()
    assert.match(await page.getByRole('timer').innerText(), /01:2[45]/)
    await page.clock.fastForward(86_000)
    await page.getByRole('dialog', { name: 'Descanso concluído' }).waitFor()
    assert.match(await page.getByRole('timer').innerText(), /00:00/)
    await page.getByRole('button', { name: 'Continuar treino', exact: true }).click()
    await expectIndex(0)
    assert.ok(await done('Agachamento búlgaro ou passada', 2).evaluate(el => el === document.activeElement))
    assert.equal(await page.getByRole('timer').count(), 0)
    await done('Agachamento búlgaro ou passada', 2).click()
    await skip()
    await done('Agachamento búlgaro ou passada', 3).click()
    assert.match(await rest.locator('.rest-next').innerText(), /Puxada com triângulo.*\nSérie 1/)
    await skip()
    await expectIndex(1)
    await done('Puxada com triângulo (pegada neutra)').click()
    assert.match(await page.getByRole('timer').innerText(), /01:15/)
    // The modal contains keyboard focus while the user rests.
    await page.keyboard.press('Tab')
    assert.ok(await rest.evaluate(el => el.contains(document.activeElement)))
    await page.keyboard.press('Escape')
    assert.equal(await page.getByRole('timer').count(), 0)
    // Unmarking never opens another rest.
    await page.getByRole('button', { name: 'Desmarcar Puxada com triângulo (pegada neutra), série 1', exact: true }).click()
    assert.equal(await page.getByRole('dialog').count(), 0)
    await feed.hover()
    await page.mouse.wheel(0, await feed.evaluate(element => element.clientHeight))
    await expectIndex(2)
    await page.locator('.feed-toolbar').getByRole('button', { name: 'Exercício anterior' }).click()
    await expectIndex(1)
    for (const width of [320, 375, 768, 1440]) {
      await page.setViewportSize({ width, height: 812 })
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Page overflow at ${width}`)
      assert.ok(await feed.evaluate(element => element.scrollWidth <= element.clientWidth), `Feed overflow at ${width}`)
    }
    await page.screenshot({ path: '/tmp/form-workout-feed-desktop.png' })
    await done('Rosca Scott com halter ou barra').click()
    await expectIndex(5)
    assert.equal(await page.getByRole('timer').count(), 0)
    await done('Tríceps francês ou no banco').click()
    assert.match(await page.getByRole('timer').innerText(), /01:00/)
    assert.match(await rest.locator('.rest-next').innerText(), /Rosca Scott.*\nSérie 2/)
    await skip()
    await expectIndex(4)
    await page.clock.fastForward(3 * 24 * 60 * 60 * 1000)
    await page.reload()
    assert.equal(await page.locator('.training-day-card').count(), 4)
    await openDay('Corpo inteiro')
    assert.equal(await page.getByRole('button', { name: 'Desmarcar Agachamento búlgaro ou passada, série 1', exact: true }).getAttribute('aria-pressed'), 'true')
    await page.getByRole('button', { name: 'Voltar aos dias de treino', exact: true }).click()
    await openDay('Superiores 1')
    await page.getByRole('button', { name: 'Retomar treino', exact: true }).click()
    await page.getByRole('heading', { name: 'Sexta-feira', exact: true }).waitFor()
    await page.getByRole('button', { name: 'English', exact: true }).click()
    assert.equal(await page.getByRole('region', { name: 'Workout exercise feed' }).count(), 1)
    assert.equal(await page.locator('.simple-feed input, .simple-feed select').count(), 0)
    await page.getByRole('button', { name: 'Finish workout', exact: true }).click()
    await page.getByRole('button', { name: 'Save & finish workout' }).click()
    await page.getByRole('dialog', { name: 'That’s work well done.' }).waitFor()
    const history = await page.evaluate(() => JSON.parse(localStorage.getItem('form:history')))
    assert.equal(history[0].sets, 5)
    assert.equal(history[0].volume, 0)
    assert.deepEqual(history[0].details.exercises[0].logs[0], { weight: '', reps: '12', done: true })
    await page.getByRole('button', { name: 'Close dialog', exact: true }).click()
    // Empty days are omitted; finishing the last prescribed set opens the review directly.
    await page.evaluate(() => {
      const days = JSON.parse(localStorage.getItem('form:days'))
      days.forEach((day, i) => { day.exercises = i === 0 ? [{ ...day.exercises[0], sets: 1 }] : [] })
      localStorage.setItem('form:days', JSON.stringify(days))
    })
    await page.reload()
    assert.equal(await page.locator('.training-day-card').count(), 1)
    await page.locator('.training-day-card').click()
    await page.getByRole('button', { name: 'Start workout', exact: true }).click()
    await page.getByRole('button', { name: 'Complete Wide-Grip Lat Pulldown set 1', exact: true }).click()
    await page.getByRole('dialog', { name: 'Ready to call it a workout?' }).waitFor()
    assert.equal(await page.getByRole('timer').count(), 0)
    await page.getByRole('button', { name: 'Save & finish workout' }).click()
    await page.getByRole('button', { name: 'Close dialog', exact: true }).click()
    await page.evaluate(() => { const days = JSON.parse(localStorage.getItem('form:days')); days.forEach(day => { day.exercises = [] }); localStorage.setItem('form:days', JSON.stringify(days)) })
    await page.reload()
    await page.getByRole('heading', { name: 'No active training days yet.' }).waitFor()
    assert.equal(await page.locator('.training-day-card').count(), 0)
    assert.deepEqual(errors, [])
    console.log('Passed: active-day cards, fixed prescriptions, completion buttons, rest modal/countdown/recovery, focus, supersets, navigation, responsive feed, translations and saved completion history.')
  } finally { await context.close() }
}
