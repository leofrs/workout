import assert from 'node:assert/strict'

export async function checkWorkoutFullscreen(browser, baseURL) {
  const context = await browser.newContext({ locale: 'pt-BR', viewport: { width: 375, height: 812 }, reducedMotion: 'reduce' })
  const page = await context.newPage()
  page.setDefaultTimeout(10_000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const focus = page.locator('.is-workout-fullscreen .daily-workout')
  const elapsed = page.getByLabel('Tempo de treino', { exact: true })
  const complete = page.getByRole('button', { name: 'Concluir Agachamento búlgaro ou passada, série 1', exact: true })
  try {
    await page.clock.install({ time: new Date('2026-11-06T12:00:00-03:00') })
    await page.goto(baseURL)
    await page.locator('.training-day-card').filter({ hasText: 'Corpo inteiro' }).click()
    assert.equal(await focus.count(), 0)
    await page.getByRole('button', { name: 'Iniciar treino', exact: true }).click()
    await focus.waitFor()
    const saved = await page.evaluate(() => localStorage.getItem('form:session'))
    assert.equal(await page.locator('.sidebar').isVisible(), false)
    assert.equal(await page.locator('.topbar').isVisible(), false)
    assert.equal(await page.locator('.active-workout-bar').isVisible(), false)
    assert.equal(await elapsed.innerText(), '00:00')
    await page.clock.fastForward(12_000)
    assert.equal(await elapsed.innerText(), '00:12')

    for (const [width, height] of [[320, 568], [375, 812], [844, 390], [768, 1024], [1440, 1000]]) {
      await page.setViewportSize({ width, height })
      await page.waitForFunction(() => {
        const bounds = document.querySelector('.is-workout-fullscreen .daily-workout')?.getBoundingClientRect()
        return bounds && bounds.x === 0 && bounds.y === 0 && Math.abs(bounds.width - innerWidth) < 1 && Math.abs(bounds.height - innerHeight) < 1
      })
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Page overflow at ${width}x${height}`)
      assert.ok(await page.locator('.training-feed').evaluate(element => element.scrollWidth <= element.clientWidth), `Feed overflow at ${width}x${height}`)
      const timer = await elapsed.boundingBox()
      assert.ok(timer && timer.y >= 0 && timer.y + timer.height < height, 'Elapsed timer stays visible')
    }
    await page.setViewportSize({ width: 375, height: 812 })
    await page.getByRole('button', { name: 'Sair da tela cheia', exact: true }).click()
    assert.equal(await focus.count(), 0)
    assert.equal(await page.evaluate(() => localStorage.getItem('form:session')), saved)
    assert.equal(await page.evaluate(() => document.documentElement.classList.contains('workout-is-fullscreen')), false)
    await page.getByRole('button', { name: 'Tela cheia', exact: true }).click()
    await focus.waitFor()
    await complete.click()
    const rest = page.getByRole('dialog', { name: 'Hora de descansar', exact: true })
    await rest.waitFor()
    assert.equal(await page.getByRole('timer').innerText(), '01:30')
    assert.equal(await rest.locator('.rest-timer-progress').getAttribute('stroke-dashoffset'), '0')
    await page.clock.fastForward(30_000)
    assert.equal(await page.getByRole('timer').innerText(), '01:00')
    const offset = Number(await rest.locator('.rest-timer-progress').getAttribute('stroke-dashoffset'))
    assert.ok(Math.abs(offset - 100 / 3) < 0.01, 'Ring follows the prescribed rest duration')
    assert.equal(await elapsed.innerText(), '00:42')
    await page.keyboard.press('Escape')
    await focus.waitFor()
    assert.equal(await page.getByRole('dialog').count(), 0, 'Escape closes rest without exiting full screen')
    await page.keyboard.press('Escape')
    assert.equal(await focus.count(), 0)
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('form:session')).logs['bulgarian-lunge'][0].done), true)
    await page.getByRole('button', { name: 'Tela cheia', exact: true }).click()
    await page.getByRole('button', { name: 'Ativar tema escuro', exact: true }).click()
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark')
    await page.getByRole('button', { name: 'English', exact: true }).click()
    await page.getByRole('button', { name: 'Exit full screen', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Finish workout', exact: true }).click()
    await page.getByRole('button', { name: 'Save & finish workout', exact: true }).click()
    await page.getByRole('dialog', { name: 'That’s work well done.' }).waitFor()
    assert.equal(await focus.count(), 0)
    assert.equal(await page.evaluate(() => document.documentElement.classList.contains('workout-is-fullscreen')), false)
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('form:history'))[0].sets), 1)
    assert.deepEqual(errors, [])
    console.log('Passed: automatic full-screen workout, visible elapsed timer, responsive viewport, exit/resume, rest progress, Escape handling, themes, language and saved completion.')
  } finally { await context.close() }
}
